import { expect, test } from "@playwright/test";

test("analyst records a changed source interpretation and reuses it on the next delivery", async ({ page }, info) => {
  const source = `synthetic-source-catalog-${info.project.name}`;
  const csv = "NPI,Site,Directory Flag\n1000000004,NORTH,Y\n1000000004,SOUTH,N\n";
  await page.goto("/?view=intake");
  await page.getByLabel("Source namespace", { exact: true }).fill(source);
  await page.getByLabel("Source file", { exact: true }).setInputFiles({ name: "synthetic-source-b.csv", mimeType: "text/csv", buffer: Buffer.from(csv) });
  await page.getByRole("button", { name: "Upload and preview" }).click();
  await expect(page.getByRole("heading", { name: "synthetic-source-b.csv" })).toBeVisible();
  const receipt = (await page.locator("#intake-receipt-detail > .iw-eyebrow").textContent())!.replace("Delivery ", "").trim();
  const before = await (await page.request.get(`/api/intakes/${receipt}`)).json();
  const panel = page.getByRole("region", { name: "Source format catalog" });
  await panel.getByRole("button", { name: "Source format catalog" }).click();
  await expect(panel.getByText("unknown", { exact: true })).toBeVisible();
  await panel.getByLabel("Row scope").selectOption("practitioner_office");
  await panel.getByRole("combobox", { name: "Source column for Practitioner NPI" }).selectOption("NPI");
  await panel.getByRole("combobox", { name: "Source column for Office identifier" }).selectOption("Site");
  await panel.getByRole("combobox", { name: "Source column for Directory visibility" }).selectOption("Directory Flag");
  await panel.getByLabel("Exact source value meaning “display”").fill("N");
  await panel.getByLabel("Exact source value meaning “exclude”").fill("Y");
  await panel.getByLabel("Source note supporting these meanings").fill("Original synthetic instructions: NPI is practitioner, Site office key, Y excludes and N displays. No network is declared.");
  await panel.getByRole("button", { name: "Preview source interpretation" }).click();
  await expect(panel.getByRole("cell", { name: "false", exact: true })).toBeVisible();
  await expect(panel.getByRole("cell", { name: "true", exact: true })).toBeVisible();
  await expect(panel.getByText(/No dataset acceptance has occurred/)).toBeVisible();
  await panel.getByRole("button", { name: "Save format proposal" }).click();
  await panel.getByLabel("Reviewer", { exact: true }).fill("Synthetic reviewer");
  await panel.getByLabel("Review reason").fill("Checked both office flags against source instructions");
  await panel.getByRole("button", { name: "Record reviewed interpretation" }).click();
  await expect(panel.getByText(/Reviewed source interpretation recorded/)).toBeVisible();
  const after = await (await page.request.get(`/api/intakes/${receipt}`)).json();
  expect(after.attempt_id).toBe(before.attempt_id);
  expect(after.state).toBe(before.state);
  expect(after.observations).toEqual(before.observations);
  await page.screenshot({ path: info.outputPath("source-format-reviewed.png"), fullPage: true });
  await panel.screenshot({ path: info.outputPath("source-format-panel.png") });
  await page.getByLabel("Source file", { exact: true }).setInputFiles({ name: "synthetic-source-c.csv", mimeType: "text/csv", buffer: Buffer.from(csv) });
  await page.getByRole("button", { name: "Upload and preview" }).click();
  await expect(page.getByRole("heading", { name: "synthetic-source-c.csv" })).toBeVisible();
  const nextPanel = page.getByRole("region", { name: "Source format catalog" });
  await nextPanel.getByRole("button", { name: "Source format catalog" }).click();
  await expect(nextPanel.getByText("exact", { exact: true })).toBeVisible();
  await page.reload();
  const reopened = page.getByRole("region", { name: "Source format catalog" });
  await reopened.getByRole("button", { name: "Source format catalog" }).click();
  await expect(reopened.getByText("exact", { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
});
